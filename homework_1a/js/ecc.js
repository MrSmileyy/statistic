/*
 * ecc.js
 * Toy elliptic curve cryptography scheme based on secp256k1.
 *
 * All arithmetic uses native JavaScript BigInt: the numbers involved
 * are 256-bit, whereas the Number type is only exact up to 2^53.
 * No external cryptographic libraries: every operation is written by hand.
 *
 * Module contents:
 *   1. secp256k1 curve parameters
 *   2. Modular arithmetic (mod, extended Euclid, inverse, power, square root)
 *   3. Group law (point addition and doubling)
 *   4. Scalar multiplication (Double-and-Add)
 *   5. Key generation (with an intentionally weak private key)
 *   6. Text -> point encoding (Koblitz method)
 *   7. EC-ElGamal encryption and decryption
 *   8. Point serialization (compressed format)
 */

const ECC = (() => {

    // =========================================================
    // 1. secp256k1 CURVE PARAMETERS
    // =========================================================
    // Weierstrass equation: y^2 = x^3 + a*x + b (mod p)
    // For secp256k1, a = 0 and b = 7, so y^2 = x^3 + 7 (mod p).
    const CURVE = {
        // Finite field prime: p = 2^256 - 2^32 - 977
        p: 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2Fn,
        a: 0n,
        b: 7n,
        // Coordinates of generator point G (fixed by the SEC 2 standard)
        Gx: 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798n,
        Gy: 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8n,
        // Order of the subgroup generated by G: n * G = O
        n: 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141n,
        // Cofactor: #E(Fp) = h * n. For secp256k1 it equals 1.
        h: 1n
    };

    const G = { x: CURVE.Gx, y: CURVE.Gy };

    // The point at infinity O (group identity element) is represented as null.
    const INFINITY = null;

    // Private key range. In a real system d would be chosen uniformly
    // in [1, n-1] (about 2^256 values). Here we intentionally restrict it
    // to [1, 50000]: this is what makes the scheme a "toy".
    const D_MIN = 1n;
    const D_MAX = 50000n;

    // Koblitz encoding parameters (see section 6)
    const KOBLITZ_K = 256n;     // attempts available per block
    const BLOCK_BYTES = 29;     // text bytes per block
    const BLOCK_PREFIX = 0x01;  // sentinel byte at the start of each block


    // =========================================================
    // 2. MODULAR ARITHMETIC
    // =========================================================

    // Non-negative reduction modulo m.
    // In JS the % operator preserves the sign of the dividend (-3n % 7n = -3n),
    // so we add m and reduce again.
    function mod(a, m = CURVE.p) {
        const r = a % m;
        return r >= 0n ? r : r + m;
    }

    // Extended Euclidean algorithm (iterative version).
    // Returns { gcd, x, y } such that a*x + b*y = gcd(a, b).
    // At each step the invariant holds:
    //   old_r = a*old_s + b*old_t   and   r = a*s + b*t
    function extendedEuclid(a, b) {
        let old_r = a, r = b;
        let old_s = 1n, s = 0n;
        let old_t = 0n, t = 1n;

        while (r !== 0n) {
            const q = old_r / r; // BigInt integer division
            [old_r, r] = [r, old_r - q * r];
            [old_s, s] = [s, old_s - q * s];
            [old_t, t] = [t, old_t - q * t];
        }
        return { gcd: old_r, x: old_s, y: old_t };
    }

    // Modular multiplicative inverse: finds x such that a*x = 1 (mod m).
    // From extended Euclid: a*x + m*y = 1  ==>  a*x = 1 (mod m).
    // Exists only if gcd(a, m) = 1; for prime m it holds for every a != 0.
    function modInverse(a, m = CURVE.p) {
        const aa = mod(a, m);
        if (aa === 0n) throw new Error("Inverse of 0 is undefined");
        const { gcd, x } = extendedEuclid(aa, m);
        if (gcd !== 1n) throw new Error("Modular inverse does not exist");
        return mod(x, m);
    }

    // Modular exponentiation via square-and-multiply.
    // This is the multiplicative counterpart of Double-and-Add.
    function modPow(base, exp, m = CURVE.p) {
        let result = 1n;
        base = mod(base, m);
        while (exp > 0n) {
            if (exp & 1n) result = (result * base) % m;
            base = (base * base) % m;
            exp >>= 1n;
        }
        return result;
    }

    // Modular square root.
    // Since p = 3 (mod 4) for secp256k1, if r is a quadratic residue
    // a root is y = r^((p+1)/4) mod p. Returns null if r is not a square.
    function modSqrt(r) {
        const y = modPow(r, (CURVE.p + 1n) / 4n);
        return mod(y * y) === mod(r) ? y : null;
    }


    // =========================================================
    // 3. GROUP LAW ON THE CURVE
    // =========================================================

    // Right-hand side of the equation: x^3 + a*x + b (mod p)
    function curveRhs(x) {
        return mod(x * x * x + CURVE.a * x + CURVE.b);
    }

    // Checks whether the point satisfies y^2 = x^3 + 7 (mod p)
    function isOnCurve(P) {
        if (P === INFINITY) return true;
        return mod(P.y * P.y) === curveRhs(P.x);
    }

    // Point negation: -P = (x, -y). Reflection across the x-axis.
    function negate(P) {
        if (P === INFINITY) return INFINITY;
        return { x: P.x, y: mod(-P.y) };
    }

    // POINT DOUBLING: R = P + P = 2P
    // Draw the tangent line to the curve at P. Its slope is obtained
    // by implicitly differentiating y^2 = x^3 + ax + b:  2y dy = (3x^2 + a) dx
    //   s  = (3*x^2 + a) / (2*y)
    //   x3 = s^2 - 2*x
    //   y3 = s*(x - x3) - y
    // The minus sign on y3 reflects the third intersection point
    // between the tangent and the curve.
    // If y = 0 the tangent is vertical and the result is O.
    function pointDouble(P) {
        if (P === INFINITY || P.y === 0n) return INFINITY;

        const num = mod(3n * P.x * P.x + CURVE.a);
        const den = modInverse(2n * P.y);
        const s = mod(num * den);

        const x3 = mod(s * s - 2n * P.x);
        const y3 = mod(s * (P.x - x3) - P.y);
        return { x: x3, y: y3 };
    }

    // POINT ADDITION: R = P + Q
    // Special cases:
    //   O + Q = Q,  P + O = P               (O is the identity element)
    //   P + (-P) = O                         (vertical line)
    //   P + P                                -> use point doubling
    // General case (P != Q): secant line through P and Q with slope
    //   s  = (yQ - yP) / (xQ - xP)
    //   x3 = s^2 - xP - xQ                   (from Vieta's formulas)
    //   y3 = s*(xP - x3) - yP                (reflection of the third point)
    function pointAdd(P, Q) {
        if (P === INFINITY) return Q;
        if (Q === INFINITY) return P;

        if (P.x === Q.x) {
            if (P.y === Q.y) return pointDouble(P);
            return INFINITY; // P and Q are inverses of each other
        }

        const num = mod(Q.y - P.y);
        const den = modInverse(Q.x - P.x);
        const s = mod(num * den);

        const x3 = mod(s * s - P.x - Q.x);
        const y3 = mod(s * (P.x - x3) - P.y);
        return { x: x3, y: y3 };
    }


    // =========================================================
    // 4. SCALAR MULTIPLICATION (DOUBLE-AND-ADD)
    // =========================================================
    // Computes k * P = P + P + ... + P (k times).
    // Adding P to itself k times would take k-1 additions, which is infeasible
    // for 256-bit k. Double-and-Add exploits the binary representation of k:
    //
    //   k = (b_{m-1} ... b_1 b_0)_2
    //
    // Iterate through bits from most significant to least significant:
    //   R = P                       (corresponds to the leading bit, always 1)
    //   for each subsequent bit b_i:
    //       R = 2R                  (DOUBLE: shift everything by one position)
    //       if b_i = 1: R = R + P   (ADD: add the bit's contribution)
    //
    // Example, k = 13 = 1101b:
    //   bit 1 -> R = P
    //   bit 1 -> R = 2P + P   = 3P
    //   bit 0 -> R = 6P
    //   bit 1 -> R = 12P + P  = 13P
    //
    // Cost: about log2(k) doublings and (number of 1-bits) additions,
    // hence O(log k) operations instead of O(k).
    //
    // If a "trace" array is passed, each step is recorded
    // so it can be displayed in the UI.
    function scalarMult(k, P, trace = null) {
        if (k < 0n) return scalarMult(-k, negate(P), trace);
        if (k === 0n || P === INFINITY) return INFINITY;

        const bits = k.toString(2);
        let R = P;
        if (trace) trace.push({ step: 0, bit: "1", op: "init", R });

        for (let i = 1; i < bits.length; i++) {
            R = pointDouble(R);
            let op = "double";
            if (bits[i] === "1") {
                R = pointAdd(R, P);
                op = "double+add";
            }
            if (trace) trace.push({ step: i, bit: bits[i], op, R });
        }
        return R;
    }


    // =========================================================
    // 5. KEY GENERATION
    // =========================================================

    // Uniform random integer in [min, max], using rejection sampling
    // to avoid modulo bias. Uses the browser's CSPRNG.
    function randomInRange(min, max) {
        const range = max - min + 1n;
        const bitLen = range.toString(2).length;
        const byteLen = Math.ceil(bitLen / 8);
        const mask = (1n << BigInt(bitLen)) - 1n;

        while (true) {
            const buf = new Uint8Array(byteLen);
            crypto.getRandomValues(buf);
            let r = 0n;
            for (const byte of buf) r = (r << 8n) | BigInt(byte);
            r &= mask;
            if (r < range) return min + r;
        }
    }

    // Role of the keys:
    //   - PRIVATE key d: a secret integer, known only to the recipient.
    //   - PUBLIC key Q = d * G: a point on the curve, published.
    // Computing Q from d is fast (Double-and-Add). The reverse step,
    // recovering d from Q and G, is the Elliptic Curve Discrete Logarithm
    // Problem (ECDLP), believed intractable when d is chosen among ~2^256
    // values. Here d is in [1, 50000]: trying all values one by one breaks it,
    // which is the intentional weakness.
    function generateKeyPair(dInput = null) {
        let d;
        if (dInput === null) {
            d = randomInRange(D_MIN, D_MAX);
        } else {
            d = BigInt(dInput);
            if (d < D_MIN || d > D_MAX) {
                throw new Error(`Private key must be between ${D_MIN} and ${D_MAX}`);
            }
        }

        const trace = [];
        const Q = scalarMult(d, G, trace);
        return { d, Q, trace };
    }


    // =========================================================
    // 6. TEXT -> POINT ENCODING (KOBLITZ METHOD)
    // =========================================================
    // ElGamal on elliptic curves encrypts POINTS, not numbers. Therefore we need
    // a reversible mapping from the message to a point on the curve.
    //
    // Koblitz's idea: given an integer m, try x-coordinates
    //   x = m*K + j    for j = 0, 1, ..., K-1
    // until x^3 + 7 is a square modulo p. About half of the elements
    // in Fp are squares, so on average 2 attempts suffice and the failure
    // probability with K = 256 is about 2^-256.
    // To decode, simply compute m = floor(x / K).
    //
    // The text is converted to UTF-8 bytes and split into 29-byte blocks.
    // Each block is prefixed with 0x01 so leading zero bytes are not lost
    // and correctness can be verified during decryption.
    // 30 bytes = 240 bits, and m*256 + 255 < 2^248 < p.

    function bytesToBigInt(bytes) {
        let r = 0n;
        for (const b of bytes) r = (r << 8n) | BigInt(b);
        return r;
    }

    function bigIntToBytes(v) {
        const out = [];
        while (v > 0n) {
            out.unshift(Number(v & 0xFFn));
            v >>= 8n;
        }
        return out;
    }

    // Returns point M and the list of attempts made (useful for teaching)
    function encodeToPoint(m) {
        const attempts = [];
        for (let j = 0n; j < KOBLITZ_K; j++) {
            const x = m * KOBLITZ_K + j;
            const rhs = curveRhs(x);
            const y = modSqrt(rhs);
            attempts.push({ j, x, rhs, ok: y !== null });
            if (y !== null) return { x, y, j, attempts };
        }
        throw new Error("Koblitz encoding failed for block");
    }

    function decodeFromPoint(M) {
        return M.x / KOBLITZ_K;
    }

    // Splits text into blocks. For each block, returns the original bytes
    // and the integer m obtained by prepending the 0x01 prefix.
    function textToBlocks(text) {
        const bytes = new TextEncoder().encode(text);
        const blocks = [];
        for (let i = 0; i < bytes.length; i += BLOCK_BYTES) {
            const data = Array.from(bytes.slice(i, i + BLOCK_BYTES));
            blocks.push({ data, m: bytesToBigInt([BLOCK_PREFIX, ...data]) });
        }
        return blocks;
    }


    // =========================================================
    // 7. EC-ELGAMAL ENCRYPTION AND DECRYPTION
    // =========================================================
    // ENCRYPTION (uses only the recipient's public key Q).
    // For each block encoded as point M:
    //   1. choose a random ephemeral nonce k in [1, n-1]
    //   2. C1 = k * G      (allows the recipient to reconstruct the secret)
    //   3. S  = k * Q      (shared secret, never transmitted)
    //   4. C2 = M + S      (the message "masked" by the secret)
    // The ciphertext is the pair (C1, C2). Using a different k for each block
    // ensures that the same plaintext produces a different ciphertext every time.
    // Each returned block includes all intermediate values so the UI
    // can display the process step by step.
    function encrypt(text, Q) {
        if (!text) throw new Error("Message is empty");
        if (!isOnCurve(Q)) throw new Error("Invalid public key");

        return textToBlocks(text).map(({ data, m }) => {
            const enc = encodeToPoint(m);
            const M = { x: enc.x, y: enc.y };
            const k = randomInRange(1n, CURVE.n - 1n);
            const C1 = scalarMult(k, G);
            const S = scalarMult(k, Q);
            const C2 = pointAdd(M, S);
            return { data, m, M, j: enc.j, attempts: enc.attempts, k, C1, S, C2 };
        });
    }

    // DECRYPTION (requires the private key d).
    // The recipient recomputes the shared secret from C1:
    //   d * C1 = d * (k * G) = k * (d * G) = k * Q = S
    // and subtracts it from C2:
    //   C2 - S = (M + S) - S = M
    // Anyone knowing only Q and C1 would have to solve ECDLP to obtain S.
    function decryptBlock(C1, C2, d) {
        const S = scalarMult(d, C1);
        const negS = negate(S);
        const M = pointAdd(C2, negS);
        if (M === INFINITY) return { S, negS, M, m: 0n, chunk: [], data: [], valid: false };

        const m = decodeFromPoint(M);
        const chunk = bigIntToBytes(m);
        // If d is wrong, M is a random point and the prefix will not match
        const valid = chunk[0] === BLOCK_PREFIX && chunk.length <= BLOCK_BYTES + 1;
        return { S, negS, M, m, chunk, data: chunk.slice(1), valid };
    }

    function decrypt(blocks, d) {
        const details = blocks.map(({ C1, C2 }) => ({ C1, C2, ...decryptBlock(C1, C2, d) }));
        const bytes = details.flatMap(b => b.data);
        const valid = details.every(b => b.valid);
        const text = new TextDecoder("utf-8", { fatal: false }).decode(new Uint8Array(bytes));
        return { text, valid, details, bytes };
    }


    // =========================================================
    // 8. POINT SERIALIZATION (SEC 1 COMPRESSED FORMAT)
    // =========================================================
    // A point can be described by x alone plus one parity bit for y:
    // given x, the two roots of x^3 + 7 are y and p - y, one even and one odd.
    // Prefix 02 = even y, 03 = odd y. Total 33 bytes.

    function toHex(v, len = 64) {
        return v.toString(16).padStart(len, "0");
    }

    function compressPoint(P) {
        const prefix = (P.y & 1n) === 0n ? "02" : "03";
        return prefix + toHex(P.x);
    }

    function decompressPoint(hex) {
        if (!/^0[23][0-9a-fA-F]{64}$/.test(hex)) {
            throw new Error("Invalid compressed point: " + hex.slice(0, 12) + "...");
        }
        const odd = hex.slice(0, 2) === "03";
        const x = BigInt("0x" + hex.slice(2));
        if (x >= CURVE.p) throw new Error("x-coordinate out of field range");

        let y = modSqrt(curveRhs(x));
        if (y === null) throw new Error("x-coordinate does not correspond to a point on the curve");
        if (((y & 1n) === 1n) !== odd) y = CURVE.p - y;
        return { x, y };
    }

    // Textual ciphertext: one block per line, each formatted as C1 || C2
    function serializeCiphertext(blocks) {
        return blocks.map(b => compressPoint(b.C1) + compressPoint(b.C2)).join("\n");
    }

    function parseCiphertext(str) {
        const lines = str.split(/\s+/).filter(l => l.length > 0);
        if (lines.length === 0) throw new Error("Ciphertext is empty");
        return lines.map(line => {
            if (line.length !== 132) throw new Error("Each block must contain 132 hexadecimal characters");
            return {
                C1: decompressPoint(line.slice(0, 66)),
                C2: decompressPoint(line.slice(66))
            };
        });
    }


    // Public module API
    return {
        CURVE, G, INFINITY, D_MIN, D_MAX, BLOCK_BYTES, BLOCK_PREFIX, KOBLITZ_K,
        mod, extendedEuclid, modInverse, modPow, modSqrt, curveRhs,
        isOnCurve, negate, pointAdd, pointDouble, scalarMult,
        randomInRange, generateKeyPair,
        textToBlocks, encodeToPoint, decodeFromPoint,
        encrypt, decrypt, decryptBlock,
        toHex, compressPoint, decompressPoint,
        serializeCiphertext, parseCiphertext
    };
})();
